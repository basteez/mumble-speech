// Builds the WebAssembly module and its JS glue into src/generated/ (specs/design.md §9.1, LD12).
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = dirname(dirname(fileURLToPath(import.meta.url)));
const root = join(pkg, '..', '..');
const out = join(pkg, 'src', 'generated');
const run = (cmd, args) => execFileSync(cmd, args, { cwd: root, stdio: 'inherit' });

run('cargo', ['build', '-p', 'mumble-wasm', '--target', 'wasm32-unknown-unknown', '--profile', 'wasm']);
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
run('wasm-bindgen', [
  join(root, 'target', 'wasm32-unknown-unknown', 'wasm', 'mumble_wasm.wasm'),
  '--target', 'web',
  '--out-dir', out,
  '--out-name', 'mumble',
  '--remove-name-section',
  '--remove-producers-section',
]);
const wasm = join(out, 'mumble_bg.wasm');
// npm workspaces hoist binaries: resolve wasm-opt from the binaryen package itself.
const require = createRequire(import.meta.url);
const binaryen = dirname(require.resolve('binaryen/package.json'));
const wasmOpt = join(binaryen, require('binaryen/package.json').bin['wasm-opt']);
run(process.execPath, [wasmOpt, '-Oz', wasm, '-o', wasm]);

const base64 = readFileSync(wasm).toString('base64');
writeFileSync(
  join(out, 'wasm-inline.ts'),
  `// Generated by scripts/build-wasm.mjs. Do not edit.\nexport const WASM_BASE64: string =\n  '${base64}';\n`,
);
for (const f of ['mumble_bg.wasm', 'mumble_bg.wasm.d.ts']) rmSync(join(out, f), { force: true });
console.log(`wasm: ${readFileSync(join(out, 'wasm-inline.ts')).length} bytes of base64 module`);
