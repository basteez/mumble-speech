//! Generates `src/fold_tables.rs` from `unicode-normalization` (specs/design.md §4.1, LD11).
//!
//! Run: `cargo run -p mumble-speech --example gen_tables`

use std::fmt::Write as _;
use unicode_normalization::char::is_combining_mark;
use unicode_normalization::UnicodeNormalization;

/// R1.4 reference: NFD, marks removed, lowercased.
fn fold(c: char) -> String {
    c.to_string().nfd().filter(|m| !is_combining_mark(*m)).flat_map(char::to_lowercase).collect()
}

/// 0–25 for `a–z`, 26–35 for `0–9`.
fn target(s: &str) -> Option<u32> {
    let mut chars = s.chars();
    match (chars.next(), chars.next()) {
        (Some(c @ 'a'..='z'), None) => Some(c as u32 - 'a' as u32),
        (Some(c @ '0'..='9'), None) => Some(26 + c as u32 - '0' as u32),
        _ => None,
    }
}

fn main() {
    let mut fold_entries = Vec::new();
    let mut ignorable: Vec<(u32, u32)> = Vec::new();
    for c in (0..=0x10ffffu32).filter_map(char::from_u32) {
        let folded = fold(c);
        if folded.is_empty() {
            match ignorable.last_mut() {
                Some((_, end)) if *end + 1 == c as u32 => *end = c as u32,
                // Surrogates are not chars: bridge the gap so ranges stay contiguous.
                Some((_, end)) if *end == 0xd7ff && c as u32 == 0xe000 => *end = c as u32,
                _ => ignorable.push((c as u32, c as u32)),
            }
        } else if !c.is_ascii() {
            if let Some(v) = target(&folded) {
                fold_entries.push(((c as u32) << 6) | v);
            }
        }
    }

    let mut out = String::from(
        "// Generated by `cargo run -p mumble-speech --example gen_tables`. Do not edit.\n\
         // Source: unicode-normalization (NFD, marks removed, lowercased), see specs/design.md §4.1.\n\n\
         /// Non-ASCII characters that fold to one of `a–z` (0–25) or `0–9` (26–35):\n\
         /// `(char << 6) | target`, sorted.\n",
    );
    writeln!(out, "pub(crate) static FOLD: [u32; {}] = [", fold_entries.len()).unwrap();
    for chunk in fold_entries.chunks(8) {
        let line: Vec<String> = chunk.iter().map(|v| format!("0x{v:07x}")).collect();
        writeln!(out, "    {},", line.join(", ")).unwrap();
    }
    out.push_str("];\n\n/// Inclusive ranges of characters that fold to nothing (combining marks), sorted.\n");
    writeln!(out, "pub(crate) static IGNORABLE: [(u32, u32); {}] = [", ignorable.len()).unwrap();
    for chunk in ignorable.chunks(4) {
        let line: Vec<String> = chunk.iter().map(|(a, b)| format!("(0x{a:05x}, 0x{b:05x})")).collect();
        writeln!(out, "    {},", line.join(", ")).unwrap();
    }
    out.push_str("];\n");

    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/src/fold_tables.rs");
    std::fs::write(path, out).expect("write fold_tables.rs");
    println!("wrote {} fold entries and {} ignorable ranges", fold_entries.len(), ignorable.len());
}
